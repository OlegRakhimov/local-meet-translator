def run(command: list[str]) -> None:
    print(">", " ".join(command), flush=True)
    subprocess.run(command, check=True)


def media_duration(path: Path) -> float:
    result = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        check=True,
        text=True,
        capture_output=True,
    )
    return float(result.stdout.strip())


def atempo_chain(ratio: float) -> str:
    filters: list[str] = []
    remaining = max(ratio, 0.5)
    while remaining > 2.0:
        filters.append("atempo=2.0")
        remaining /= 2.0
    filters.append(f"atempo={remaining:.8f}")
    return ",".join(filters)


async def synthesize_all() -> None:
    for index, _start, _end, text in SCENES:
        destination = BUILD / f"scene_{index:02d}.mp3"
        print(f"[{index:02d}/{len(SCENES):02d}] Генерация речи", flush=True)
        communicator = edge_tts.Communicate(
            text=text,
            voice=VOICE,
            rate=RATE,
            pitch=PITCH,
        )
        await communicator.save(str(destination))


def build_fixed_scene_audio(index: int, start: float, end: float) -> Path:
    source = BUILD / f"scene_{index:02d}.mp3"
    target = BUILD / f"scene_{index:02d}_fixed.wav"
    scene_duration = end - start
    source_duration = media_duration(source)
    usable = max(scene_duration - START_PAUSE_SECONDS - END_MARGIN_SECONDS, 1.0)
    filters: list[str] = []
    if source_duration > usable:
        filters.append(atempo_chain(source_duration / usable))
    filters.extend(
        [
            f"adelay={int(START_PAUSE_SECONDS * 1000)}:all=1",
            f"apad=pad_dur={scene_duration:.3f}",
            f"atrim=0:{scene_duration:.3f}",
            "asetpts=N/SR/TB",
            "aresample=48000",
        ]
    )
    run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(source),
            "-af",
            ",".join(filters),
            "-ac",
            "2",
            "-ar",
            "48000",
            "-c:a",
            "pcm_s16le",
            str(target),
        ]
    )
    return target


def main() -> None:
    BUILD.mkdir(parents=True, exist_ok=True)
    asyncio.run(synthesize_all())
    fixed = [build_fixed_scene_audio(i, s, e) for i, s, e, _ in SCENES]
    concat_file = BUILD / "concat.txt"
    concat_file.write_text(
        "".join(f"file '{path.as_posix()}'\n" for path in fixed),
        encoding="utf-8",
    )
    run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(concat_file),
            "-t",
            "600",
            "-c:a",
            "aac",
            "-b:a",
            "192k",
            "-ar",
            "48000",
            "-movflags",
            "+faststart",
            str(OUTPUT),
        ]
    )
    print(f"Готово: {OUTPUT} ({OUTPUT.stat().st_size / 1024 / 1024:.1f} MB)", flush=True)


if __name__ == "__main__":
    main()
